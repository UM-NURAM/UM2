#!/usr/bin/env python3
"""Synchronize um2.openmc with a pinned release of OpenMC.

um2.openmc is a hand-written re-implementation of the subset of the OpenMC
Python API that UM2 supports (multigroup cross sections, materials and 2D
geometry). This tool keeps it in sync with the OpenMC release referenced by the
``extern/openmc`` git submodule, without importing (or installing) OpenMC:

``generate``
    Regenerate the data tables that um2.openmc takes verbatim from OpenMC
    (natural abundances, atomic masses, energy group structures).

``check-api``
    Compare the signatures of every public class, method and function in
    um2.openmc against the corresponding definition in the OpenMC source and
    report differences. Exits with a non-zero status if an implemented function
    or method has a signature that differs from OpenMC, so that API drift is
    detected when the submodule is updated.

Typical workflow when a new OpenMC release comes out::

    git -C extern/openmc fetch --tags && git -C extern/openmc checkout vX.Y.Z
    python python/tools/sync_openmc.py generate
    python python/tools/sync_openmc.py check-api

"""

from __future__ import annotations

import argparse
import ast
import inspect
import pprint
import shutil
import sys
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OPENMC_SRC = REPO_ROOT / "extern" / "openmc"
PACKAGE_DIR = REPO_ROOT / "python" / "um2" / "openmc"

HEADER = '''"""GENERATED FILE -- DO NOT EDIT.

Generated by python/tools/sync_openmc.py from OpenMC {version}
({source}).
"""
'''


def openmc_version(openmc_src: Path) -> str:
    """Return a description of the OpenMC version in openmc_src."""
    import subprocess

    try:
        out = subprocess.run(
            ["git", "-C", str(openmc_src), "describe", "--tags", "--always"],
            check=True, capture_output=True, text=True)
        return out.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown version"


# ==============================================================================
# generate
# ==============================================================================

def _module_ast(path: Path) -> ast.Module:
    return ast.parse(path.read_text(), filename=str(path))


def _literal_assignment(module: ast.Module, name: str):
    """Return the literal value assigned to a top-level variable."""
    for node in module.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == name:
                    return ast.literal_eval(node.value)
        elif isinstance(node, ast.AnnAssign):
            if isinstance(node.target, ast.Name) and node.target.id == name:
                return ast.literal_eval(node.value)
    raise KeyError(f"{name} not found")


def _group_structures(module: ast.Module) -> dict[str, list[float]]:
    """Extract GROUP_STRUCTURES['name'] = np.array([...]) assignments."""
    result = {}
    for node in module.body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        if not (isinstance(target, ast.Subscript)
                and isinstance(target.value, ast.Name)
                and target.value.id == "GROUP_STRUCTURES"):
            continue
        key = ast.literal_eval(target.slice)
        value = node.value
        if not (isinstance(value, ast.Call) and len(value.args) == 1
                and ast.unparse(value.func) in ("np.array", "numpy.array")):
            raise ValueError(f"Unexpected definition of GROUP_STRUCTURES[{key!r}]: "
                             f"{ast.unparse(value)}")
        result[key] = [float(x) for x in ast.literal_eval(value.args[0])]
    if not result:
        raise ValueError("No GROUP_STRUCTURES found")
    return result


def generate(openmc_src: Path, package_dir: Path = PACKAGE_DIR) -> list[Path]:
    """Regenerate the data tables. Returns the list of written files."""
    pkg = openmc_src / "openmc"
    version = openmc_version(openmc_src)
    written = []

    # Natural abundances
    data_ast = _module_ast(pkg / "data" / "data.py")
    abundance = _literal_assignment(data_ast, "NATURAL_ABUNDANCE")
    path = package_dir / "data" / "_natural_abundance.py"
    path.write_text(
        HEADER.format(version=version, source="openmc/data/data.py")
        + "\nNATURAL_ABUNDANCE = "
        + pprint.pformat(abundance, sort_dicts=False, width=79)
        + "\n")
    written.append(path)

    # Atomic masses (AME2020), copied verbatim
    src = pkg / "data" / "mass_1.mas20.txt"
    path = package_dir / "data" / "mass_1.mas20.txt"
    shutil.copyfile(src, path)
    written.append(path)

    # Energy group structures
    groups_ast = _module_ast(pkg / "mgxs" / "__init__.py")
    structures = _group_structures(groups_ast)
    lines = [HEADER.format(version=version, source="openmc/mgxs/__init__.py"),
             "", "GROUP_STRUCTURES_DATA = {"]
    for key, values in structures.items():
        body = pprint.pformat(values, width=75, compact=True)
        body = body.replace("\n", "\n    ")
        lines.append(f"    {key!r}: {body},")
    lines.append("}")
    path = package_dir / "mgxs" / "_group_structures.py"
    path.write_text("\n".join(lines) + "\n")
    written.append(path)

    # Record the version that the tables were generated from
    path = package_dir / "_openmc_version.py"
    path.write_text(HEADER.format(version=version, source="git describe")
                    + f"\nOPENMC_VERSION = {version!r}\n")
    written.append(path)
    return written


