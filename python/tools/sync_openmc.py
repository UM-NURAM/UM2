# check-api
# ==============================================================================

@dataclass
class Param:
    name: str
    kind: str        # 'positional', 'vararg', 'keyword_only', 'varkw'
    default: str | None  # source text of the default, or None if required

    def __str__(self) -> str:
        prefix = {"vararg": "*", "varkw": "**"}.get(self.kind, "")
        text = prefix + self.name
        if self.default is not None:
            text += "=" + self.default
        return text


@dataclass
class Definition:
    qualname: str
    path: Path
    params: list[Param] | None = None  # None for classes
    methods: dict[str, "Definition"] = field(default_factory=dict)
    properties: set[str] = field(default_factory=set)
    bases: list[str] = field(default_factory=list)


def _params_from_ast(args: ast.arguments, skip_first: bool) -> list[Param]:
    positional = list(args.posonlyargs) + list(args.args)
    defaults = [None] * (len(positional) - len(args.defaults)) + list(args.defaults)
    params = []
    for arg, default in zip(positional, defaults):
        params.append(Param(arg.arg, "positional",
                            None if default is None else ast.unparse(default)))
    if args.vararg is not None:
        params.append(Param(args.vararg.arg, "vararg", None))
    for arg, default in zip(args.kwonlyargs, args.kw_defaults):
        params.append(Param(arg.arg, "keyword_only",
                            None if default is None else ast.unparse(default)))
    if args.kwarg is not None:
        params.append(Param(args.kwarg.arg, "varkw", None))
    if skip_first and params and params[0].kind == "positional":
        params = params[1:]
    return params


def _is_property(node: ast.FunctionDef) -> bool:
    for dec in node.decorator_list:
        text = ast.unparse(dec)
        if text == "property" or text.endswith(".setter") or text.endswith(".getter"):
            return True
    return False


def _is_static(node: ast.FunctionDef) -> bool:
    return any(ast.unparse(d) == "staticmethod" for d in node.decorator_list)


def index_openmc(openmc_src: Path) -> dict[str, list[Definition]]:
    """Index every top-level class and function in the OpenMC package by name."""
    index: dict[str, list[Definition]] = {}
    pkg = openmc_src / "openmc"
    for path in sorted(pkg.rglob("*.py")):
        try:
            module = _module_ast(path)
        except SyntaxError:
            continue
        for node in module.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                d = Definition(node.name, path, _params_from_ast(node.args, False))
                index.setdefault(node.name, []).append(d)
            elif isinstance(node, ast.ClassDef):
                d = Definition(node.name, path,
                               bases=[ast.unparse(b) for b in node.bases])
                for item in node.body:
                    if not isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                        continue
                    if _is_property(item):
                        d.properties.add(item.name)
                        continue
                    skip = not _is_static(item)
                    d.methods[item.name] = Definition(
                        f"{node.name}.{item.name}", path,
                        _params_from_ast(item.args, skip))
                index.setdefault(node.name, []).append(d)
    return index


def _resolve_inherited(defn: Definition, index: dict[str, list[Definition]],
                       seen: set[str] | None = None) -> Definition:
    """Return a copy of defn with methods/properties inherited from its bases."""
    seen = set() if seen is None else seen
    merged = Definition(defn.qualname, defn.path, methods={}, properties=set())
    for base in defn.bases:
        name = base.split(".")[-1].split("[")[0]
        if name in seen or name not in index:
            continue
        seen.add(name)
        parent = _resolve_inherited(index[name][0], index, seen)
        merged.methods.update(parent.methods)
        merged.properties |= parent.properties
    merged.methods.update(defn.methods)
    merged.properties |= defn.properties
    return merged


def _params_from_callable(obj, skip_first: bool) -> list[Param] | None:
    try:
        sig = inspect.signature(obj)
    except (TypeError, ValueError):
        return None
    kinds = {
        inspect.Parameter.POSITIONAL_ONLY: "positional",
        inspect.Parameter.POSITIONAL_OR_KEYWORD: "positional",
        inspect.Parameter.VAR_POSITIONAL: "vararg",
        inspect.Parameter.KEYWORD_ONLY: "keyword_only",
        inspect.Parameter.VAR_KEYWORD: "varkw",
    }
    params = []
    for p in sig.parameters.values():
        default = None if p.default is inspect.Parameter.empty else repr(p.default)
        params.append(Param(p.name, kinds[p.kind], default))
    if skip_first and params and params[0].kind == "positional":
        params = params[1:]
    return params


def _compare_params(ours: list[Param], theirs: list[Param]) -> list[str]:
    """Compare parameter lists by name, kind and presence of a default."""
    problems = []
    ours_named = {p.name: p for p in ours}
    theirs_named = {p.name: p for p in theirs}
    for p in theirs:
        if p.name not in ours_named:
            # An OpenMC *args/**kwargs can be absorbed by our own **kwargs
            if not any(q.kind == "varkw" for q in ours):
                problems.append(f"missing parameter '{p}'")
            continue
        q = ours_named[p.name]
        if (p.default is None) != (q.default is None):
            problems.append(f"parameter '{p.name}': OpenMC has '{p}', UM2 has '{q}'")
    for q in ours:
        if q.name not in theirs_named and q.kind not in ("varkw", "vararg"):
            if q.default is None:
                problems.append(f"extra required parameter '{q}'")
    # Positional order must agree for the parameters we share
    shared_theirs = [p.name for p in theirs if p.kind == "positional"
                     and p.name in ours_named]
    shared_ours = [q.name for q in ours if q.kind == "positional"
                   and q.name in theirs_named]
    if shared_theirs != shared_ours:
        problems.append(f"positional order differs: OpenMC {shared_theirs}, "
                        f"UM2 {shared_ours}")
    return problems


# Public names in um2.openmc that are intentionally not in OpenMC, or whose
# signatures intentionally differ. Values are the reason.
ALLOWED_DIFFERENCES: dict[str, str] = {
}


# Subpackages of OpenMC whose definitions are never the ones um2.openmc mirrors
_IGNORED_SUBPACKAGES = {"lib", "deplete", "examples", "openmoc_compatible"}


def _rank_candidates(candidates, modname, openmc_src):
    """Order the OpenMC definitions of a name so that the most likely match for
    a um2.openmc module comes first (e.g. openmc.Material rather than
    openmc.lib.Material)."""
    sub = modname.split(".")[2] if modname.count(".") >= 2 else None

    def rank(defn):
        parts = defn.path.relative_to(openmc_src / "openmc").parts
        if parts[0] in _IGNORED_SUBPACKAGES:
            return 2
        if sub is not None:
            return 0 if parts[0] == sub else 1
        return 0 if len(parts) == 1 else 1
    return sorted(candidates, key=rank)


def _public_members(module):
    names = getattr(module, "__all__", None)
    if names is None:
        names = [n for n in dir(module) if not n.startswith("_")]
    for name in names:
        yield name, getattr(module, name)


def check_api(openmc_src: Path, verbose: bool = False) -> int:
    """Check um2.openmc signatures against OpenMC. Returns the number of errors."""
    sys.path.insert(0, str(REPO_ROOT / "python"))
    import importlib

    index = index_openmc(openmc_src)
    modules = ["um2.openmc", "um2.openmc.model", "um2.openmc.mgxs",
               "um2.openmc.data", "um2.openmc.stats"]
    errors: list[str] = []
    notes: list[str] = []
    checked = 0
    seen_objects = set()
    for modname in modules:
        module = importlib.import_module(modname)
        for name, obj in _public_members(module):
            if not (inspect.isclass(obj) or inspect.isfunction(obj)):
                continue
            if id(obj) in seen_objects:
                continue
            seen_objects.add(id(obj))
            label = f"{modname}.{name}"
            if label in ALLOWED_DIFFERENCES or name in ALLOWED_DIFFERENCES:
                continue
            if name not in index:
                notes.append(f"{label}: not found in OpenMC")
                continue
            candidates = _rank_candidates(index[name], modname, openmc_src)
            if getattr(obj, "_um2_unsupported", False):
                continue
            stub = getattr(obj, "_um2_stub", False)
            if stub:
                # Stubs accept (and ignore) any arguments
                continue
            if inspect.isfunction(obj):
                theirs = next((c for c in candidates if c.params is not None), None)
                if theirs is None:
                    notes.append(f"{label}: is a class in OpenMC")
                    continue
                ours = _params_from_callable(obj, False)
                checked += 1
                for problem in _compare_params(ours, theirs.params):
                    errors.append(f"{label}: {problem}")
                continue
            # Class
            theirs = next((c for c in candidates if c.params is None), None)
            if theirs is None:
                notes.append(f"{label}: is a function in OpenMC")
                continue
            theirs = _resolve_inherited(theirs, index)
            for meth_name, meth in theirs.methods.items():
                if meth_name.startswith("_") and meth_name != "__init__":
                    continue
                attr = inspect.getattr_static(obj, meth_name, None)
                if attr is None:
                    if not stub:
                        notes.append(f"{label}.{meth_name}: not implemented")
                    continue
                is_static = isinstance(attr, staticmethod)
                func = getattr(obj, meth_name)
                if isinstance(attr, property) or not callable(func):
                    errors.append(f"{label}.{meth_name}: is a method in OpenMC")
                    continue
                if meth_name == "__init__" and func is object.__init__:
                    continue
                skip = not is_static and not isinstance(attr, classmethod)
                ours = _params_from_callable(func, skip)
                if ours is None:
                    continue
                checked += 1
                for problem in _compare_params(ours, meth.params):
                    errors.append(f"{label}.{meth_name}: {problem}")
            if not stub:
                for prop in sorted(theirs.properties):
                    if prop.startswith("_"):
                        continue
                    if inspect.getattr_static(obj, prop, None) is None:
                        notes.append(f"{label}.{prop}: property not implemented")

    print(f"Checked {checked} signatures against OpenMC {openmc_version(openmc_src)}")
    if verbose:
        for note in notes:
            print(f"  note: {note}")
    for error in errors:
        print(f"  ERROR: {error}")
    print(f"{len(errors)} error(s), {len(notes)} note(s)"
          + ("" if verbose else " (use -v to show notes)"))
    return len(errors)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--openmc-src", type=Path, default=DEFAULT_OPENMC_SRC,
                        help="Path to the OpenMC source tree (default: extern/openmc)")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("generate", help="Regenerate data tables from OpenMC")
    check = sub.add_parser("check-api", help="Compare um2.openmc signatures to OpenMC")
    check.add_argument("-v", "--verbose", action="store_true")
    args = parser.parse_args(argv)

    if not (args.openmc_src / "openmc" / "__init__.py").exists():
        parser.error(f"OpenMC source not found at {args.openmc_src}. "
                     "Run 'git submodule update --init extern/openmc'.")
    if args.command == "generate":
        for path in generate(args.openmc_src):
            print(f"wrote {path.relative_to(REPO_ROOT)}")
        return 0
    return 1 if check_api(args.openmc_src, args.verbose) else 0


if __name__ == "__main__":
    sys.exit(main())
